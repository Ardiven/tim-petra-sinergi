<script>
    // Check if background image loads successfully
    function checkImageLoad() {
        const testImg = new Image();
        testImg.onload = function() {
            console.log('Background image loaded successfully');
        };
        testImg.onerror = function() {
            console.warn('Background image failed to load, using fallback');
            // Switch to fallback background
            const bgElement = document.querySelector('.bg-classroom');
            if (bgElement) {
                bgElement.classList.remove('bg-classroom');
                bgElement.classList.add('bg-fallback');
            }
        };
        testImg.src = 'assets/img/astor25.jpg';
    }

    // Run check when page loads
    document.addEventListener('DOMContentLoaded', checkImageLoad);
</script>